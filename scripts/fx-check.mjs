import { chromium } from 'playwright-core'
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH })
const errs = []
const p = await b.newPage({ viewport: { width: 1280, height: 800 } })
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
p.on('pageerror', (e) => errs.push(String(e)))
await p.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
await p.keyboard.press('Control+k')
await p.waitForTimeout(400)
await p.screenshot({ path: 'shots/fx-palette.png' })
await p.keyboard.type('ope')
await p.waitForTimeout(200)
await p.screenshot({ path: 'shots/fx-palette-filter.png' })
await p.keyboard.press('Enter')
await p.waitForTimeout(1200)
console.log('active nav:', await p.$eval('.nav__links a[aria-current]', (e) => e.textContent).catch(() => 'none'))
await p.screenshot({ path: 'shots/fx-opensource.png' })
await p.keyboard.type('sakura')
await p.waitForTimeout(1500)
await p.screenshot({ path: 'shots/fx-sakura.png' })
await p.waitForTimeout(6000)
console.log('petals removed:', (await p.$('canvas.petals')) === null)
await p.keyboard.press('t')
await p.waitForTimeout(250)
await p.screenshot({ path: 'shots/fx-theme-mid.png' })
await p.waitForTimeout(800)
console.log('theme:', await p.evaluate(() => document.documentElement.dataset.theme))
await p.keyboard.type('hire')
await p.waitForTimeout(1200)
await p.screenshot({ path: 'shots/fx-hire.png' })
const m = await b.newPage({ viewport: { width: 390, height: 800 } })
await m.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await m.waitForTimeout(1200)
await m.screenshot({ path: 'shots/fx-mobile-top.png' })
await m.click('.kbar')
await m.waitForTimeout(400)
await m.screenshot({ path: 'shots/fx-mobile-palette.png' })
console.log('errors:', errs.length ? errs : 'none')
await b.close()
